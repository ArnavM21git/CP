#include <bits/stdc++.h>
using namespace std;

// 1. Typedefs for faster typing
using ll = long long;
using vi = vector<int>;

// 2. Fast I/O (crucial for competitive programming)
void fast_io() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
}

void solve() {
    int n;cin>>n;
    vector<int> a(n);
    for(auto &x:a) cin>>x;
    ll sum=a[0];ll mx=a[0];
    for(int i=1;i<n;i++)
    {
        if(sum<0) sum=0;
        if(abs(a[i])%2==abs(a[i-1])%2)
        {
            sum=a[i];
        }
        else{
            sum+=a[i];
        }
        mx=max(mx,sum);
    }
    cout<<mx<<endl;
}

int main() {
    fast_io();
    int t = 1;
    cin >> t;
    while (t--) {
        solve();
    }
    return 0;
}