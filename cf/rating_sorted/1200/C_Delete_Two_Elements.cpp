void solve() {
    ll n;cin>>n;
    vector<ll> a(n);
    ll sum=0;
    for(auto &x:a) {cin>>x;sum+=x;}
    if(2*sum %n!=0) {cout<<0<<endl;return;}
    ll t=((2*sum)/n);
    unordered_map<ll,ll> mp;
    ll c=0;
    for(ll x:a)
    {
        if(mp[t-x]!=0) 
        {
            c+=mp[t-x];
        }
        mp[x]++;
    }
    cout<<c<<endl;
}

