void solve() {
    int n;cin>>n;
    vector<string> s(n);
    for(auto &x:s) cin>>x;

    auto sn=[&](int u,int v){
        if(u<v){
            if(s[u][v]=='1') return true;
            else return false;
        }
        else{
            if(s[u][v]=='0') return true;
            else return false;
        }
    };

        vector<int> a;
        for(int i=0;i<n;i++) a.push_back(i);
        sort(a.begin(),a.end(),sn);
        for(int x:a) cout<<x+1<<" ";
        cout<<endl;
}

int main() {
    fast_io();
    int t = 1;
    cin >> t;
    while (t--) {
        solve();
    }
    return 0;
}